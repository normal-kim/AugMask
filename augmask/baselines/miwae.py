"""MIWAE baseline (Mattei & Frellsen, 2019) used as a generator.

Architecture and training follow the hyperimpute MIWAE imputer: two-layer ReLU
encoder/decoder, Gaussian q(z|x), Student-t p(x|z) for numerical features, the
importance-weighted bound over the observed entries, Adam (lr 1e-3), batch 256,
zero-filled inputs. Categorical features get a softmax head and one-hot inputs.
Settings from Appendix C.6: 800 epochs, latent size 64, hidden width 256, K = 40.
Samples are generated by drawing z from the prior and x from p(x|z).

Inputs and outputs live in the scenario's model space (see augmask.data.scenario).
"""
from __future__ import annotations

import math

import numpy as np
import torch
import torch.nn.functional as F
from torch import nn
from torch.distributions import Normal, StudentT



def _mlp(d_in: int, h: int, d_out: int) -> nn.Sequential:
    net = nn.Sequential(nn.Linear(d_in, h), nn.ReLU(), nn.Linear(h, h), nn.ReLU(), nn.Linear(h, d_out))
    for m in net:
        if isinstance(m, nn.Linear):
            nn.init.xavier_uniform_(m.weight)
    return net


class _MIWAENet(nn.Module):
    def __init__(self, d_num: int, n_categories: list[int], latent: int, hidden: int):
        super().__init__()
        self.d_num, self.n_categories, self.latent = d_num, list(n_categories), latent
        d_in = d_num + sum(n_categories)
        self.encoder = _mlp(d_in, hidden, 2 * latent)
        self.decoder = _mlp(latent, hidden, 3 * d_num + sum(n_categories))

    def _inputs(self, x_num, x_cat, m_num, m_cat):
        parts = [x_num * m_num]
        for k, n in enumerate(self.n_categories):
            parts.append(F.one_hot(x_cat[:, k].clamp(min=0), n).float() * m_cat[:, k:k + 1])
        return torch.cat(parts, dim=1)

    def _decode(self, z):
        out = self.decoder(z)
        d = self.d_num
        loc, scale, df = out[..., :d], F.softplus(out[..., d:2 * d]) + 1e-3, F.softplus(out[..., 2 * d:3 * d]) + 3
        logits = torch.split(out[..., 3 * d:], self.n_categories, dim=-1) if self.n_categories else ()
        return loc, scale, df, logits

    def neg_bound(self, x_num, x_cat, m_num, m_cat, K: int):
        enc = self.encoder(self._inputs(x_num, x_cat, m_num, m_cat))
        q = Normal(enc[:, :self.latent], F.softplus(enc[:, self.latent:]) + 1e-4)
        z = q.rsample((K,))  # [K, B, latent]
        loc, scale, df, logits = self._decode(z)
        log_px = (StudentT(df, loc, scale).log_prob(x_num) * m_num).sum(-1)
        for k, lg in enumerate(logits):
            ll = torch.log_softmax(lg, -1).gather(-1, x_cat[:, k].clamp(min=0).expand(K, -1).unsqueeze(-1)).squeeze(-1)
            log_px = log_px + ll * m_cat[:, k]
        log_pz = Normal(0.0, 1.0).log_prob(z).sum(-1)
        log_qz = q.log_prob(z).sum(-1)
        return -(torch.logsumexp(log_px + log_pz - log_qz, dim=0) - math.log(K)).mean()

    @torch.no_grad()
    def sample(self, n: int, device):
        z = torch.randn(n, self.latent, device=device)
        loc, scale, df, logits = self._decode(z)
        x_num = StudentT(df, loc, scale).sample()
        x_cat = [torch.distributions.Categorical(logits=lg).sample() for lg in logits]
        x_cat = torch.stack(x_cat, 1) if x_cat else torch.zeros(n, 0, dtype=torch.long, device=device)
        return x_num, x_cat


class MIWAE:
    def __init__(self, n_epochs: int = 800, latent_size: int = 64, n_hidden: int = 256, K: int = 40,
                 batch_size: int = 256, lr: float = 1e-3, seed: int = 0, device: str | None = None):
        self.n_epochs, self.latent_size, self.n_hidden, self.K = n_epochs, latent_size, n_hidden, K
        self.batch_size, self.lr, self.seed = batch_size, lr, seed
        self.device = torch.device(device or ("cuda" if torch.cuda.is_available() else "cpu"))

    def fit(self, X_num, X_cat, M_num, M_cat, n_categories) -> "MIWAE":
        torch.manual_seed(self.seed)
        rng = np.random.default_rng(self.seed)
        dev = self.device
        t = lambda a, dt: torch.as_tensor(np.asarray(a), dtype=dt, device=dev)
        x_num, x_cat = t(np.where(M_num, X_num, 0.0), torch.float32), t(np.where(M_cat, X_cat, 0), torch.long)
        m_num, m_cat = t(M_num, torch.float32), t(M_cat, torch.float32)
        self.net_ = _MIWAENet(x_num.shape[1], list(n_categories), self.latent_size, self.n_hidden).to(dev)
        opt = torch.optim.Adam(self.net_.parameters(), lr=self.lr)
        n = len(x_num)
        self.history_ = []
        for epoch in range(self.n_epochs):
            perm = torch.as_tensor(rng.permutation(n), device=dev)
            total = torch.zeros((), device=dev)
            for idx in torch.split(perm, min(self.batch_size, n)):
                loss = self.net_.neg_bound(x_num[idx], x_cat[idx], m_num[idx], m_cat[idx], self.K)
                opt.zero_grad()
                loss.backward()
                opt.step()
                total += loss.detach() * len(idx)
            self.history_.append({"epoch": epoch + 1, "neg_bound": (total / n).item()})
        return self

    def sample(self, n: int) -> tuple[np.ndarray, np.ndarray]:
        torch.manual_seed(self.seed)
        self.net_.eval()
        x_num, x_cat = self.net_.sample(n, self.device)
        return x_num.cpu().numpy(), x_cat.cpu().numpy()
